package com.cheatbreaker.client.render;

public class ColorState {
   public float floatValue = 1.0F;
   public float floatValue2 = 1.0F;
   public float floatValue3 = 1.0F;
   public float floatValue4 = 1.0F;

   public ColorState() {
   }

   public ColorState(float f, float f2, float f3, float f4) {
      this.floatValue = f;
      this.floatValue2 = f2;
      this.floatValue3 = f3;
      this.floatValue4 = f4;
   }
}
